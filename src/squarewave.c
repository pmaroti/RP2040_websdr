/*
 * PIO square wave output. The PIO state machine toggles the pin from a tight
 * loop and the clock divider sets the frequency (same technique as
 * pmaroti/am_generator). The divider has 8 fractional bits, so frequencies
 * that need a fractional divider have up to one system clock of edge jitter.
 *
 * ---------------------------------------------------------------------------
 * Frequency math
 * ---------------------------------------------------------------------------
 *
 *   f_out = clk_sys / (cycles * div)
 *
 *   clk_sys  system clock, 125 MHz by default
 *   cycles   PIO clocks per output period: 2 (fast program) or 64 (slow)
 *   div      state machine clock divider, 1.0 .. 65535.996 in 1/256 steps
 *
 * So for a requested frequency f:   div = clk_sys / (cycles * f)
 *
 * Example, 7.1 MHz on the fast program:
 *   div = 125e6 / (2 * 7.1e6) = 8.80282
 *   in 1/256 steps: 8.80282 * 256 = 2253.5 -> rounds to 2254 = 8 + 206/256
 *   actual: 125e6 * 256 / (2 * 2254) = 7,098,491.6 Hz
 *
 * Fractional dividers: the hardware gets the fractional part by making some
 * PIO clocks one system clock longer than others. The average frequency is
 * exact, but individual edges can be off by up to one system clock (8 ns at
 * 125 MHz). When clk_sys / (cycles * f) is a whole number (e.g. 1 kHz,
 * 10 kHz, 6.25 MHz) there is no jitter at all.
 */

#include "pico/stdlib.h"
#include "hardware/clocks.h"    // clock_get_hz(clk_sys)
#include "hardware/pio.h"       // PIO state machine API

#include "squarewave.h"
#include "squarewave.pio.h"     // generated from squarewave.pio at build time

#define FAST_CYCLES     2       // PIO clocks per period, squarewave
#define SLOW_CYCLES     64      // PIO clocks per period, squarewave_slow
#define SLOW_BELOW_HZ   10000.0 // use the slow program below this frequency
#define DIV_MAX         65535.996   // largest divider: 65535 + 255/256

// Which PIO block and state machine we use. The RP2040 has two PIO blocks
// (pio0, pio1) with four state machines each; only one is needed here.
static PIO pio = pio0;
static uint sm;                     // state machine index, claimed at init

static uint pin;                    // output GPIO

// Where each program was loaded in the PIO's 32-word instruction memory.
// Both are loaded once at startup and stay there, so switching between them
// never runs out of instruction memory.
static uint offset_fast, offset_slow;

static int running_program = -1;    // -1 stopped, else cycles per period
static double current_hz;           // frequency being produced, 0 = off

void squarewave_init(unsigned int out_pin) {
    pin = out_pin;

    // Copy both programs into PIO instruction memory.
    offset_fast = pio_add_program(pio, &squarewave_program);
    offset_slow = pio_add_program(pio, &squarewave_slow_program);

    // Reserve a free state machine (panic if none, which can't happen here).
    sm = pio_claim_unused_sm(pio, true);

    // Until a frequency is set the pin is an ordinary GPIO output, driven low.
    gpio_init(pin);
    gpio_set_dir(pin, GPIO_OUT);
    gpio_put(pin, 0);

    // Strongest drive and fast edges, for the cleanest square wave at high
    // frequencies. (These pad settings stay in effect when PIO takes over.)
    gpio_set_drive_strength(pin, GPIO_DRIVE_STRENGTH_12MA);
    gpio_set_slew_rate(pin, GPIO_SLEW_RATE_FAST);
}

// Slowest possible: slow program at the largest divider.
double squarewave_min_hz(void) {
    return clock_get_hz(clk_sys) / (SLOW_CYCLES * DIV_MAX);
}

// Fastest possible: fast program at divider 1.
double squarewave_max_hz(void) {
    return clock_get_hz(clk_sys) / (double)FAST_CYCLES;
}

/*
 * (Re)start the state machine with one of the two programs.
 *
 * Used when the output is off or when switching between the fast and slow
 * program. pio_sm_init() resets the state machine and jumps to the program's
 * first instruction, so this can cause one short glitch on the pin.
 */
static void start_program(int cycles, uint16_t div_int, uint8_t div_frac) {
    uint offset = (cycles == FAST_CYCLES) ? offset_fast : offset_slow;

    // Default config generated by pioasm for this program (sets the wrap
    // points), then our settings on top.
    pio_sm_config c = (cycles == FAST_CYCLES)
        ? squarewave_program_get_default_config(offset)
        : squarewave_slow_program_get_default_config(offset);

    pio_sm_set_enabled(pio, sm, false);             // stop before reconfiguring
    sm_config_set_set_pins(&c, pin, 1);             // "set pins" drives 1 pin starting at `pin`
    sm_config_set_clkdiv_int_frac8(&c, div_int, div_frac);
    pio_gpio_init(pio, pin);                        // hand the pin over to this PIO block
    pio_sm_init(pio, sm, offset, &c);               // load config, reset, go to program start
    pio_sm_set_enabled(pio, sm, true);              // run
    running_program = cycles;
}

double squarewave_set(double freq_hz) {
    // 0 = off: stop the state machine and give the pin back to normal GPIO,
    // driven low, so the output is a defined level rather than wherever the
    // PIO left it.
    if (freq_hz == 0) {
        pio_sm_set_enabled(pio, sm, false);
        gpio_init(pin);
        gpio_set_dir(pin, GPIO_OUT);
        gpio_put(pin, 0);
        running_program = -1;
        current_hz = 0;
        return 0;
    }

    // Written as !(in range) so that NaN is rejected too.
    if (!(freq_hz >= squarewave_min_hz() && freq_hz <= squarewave_max_hz())) {
        return -1;
    }

    double clk = clock_get_hz(clk_sys);
    int cycles = (freq_hz < SLOW_BELOW_HZ) ? SLOW_CYCLES : FAST_CYCLES;

    // Divider in 16.8 fixed point, rounded to nearest.
    // (Integer part in the upper bits, 1/256ths in the low 8 bits.)
    double div = clk / (cycles * freq_hz);
    uint32_t div_fixed = (uint32_t)(div * 256.0 + 0.5);

    // Clamp to what the hardware accepts: 1.0 .. 65535 + 255/256.
    if (div_fixed < 256) div_fixed = 256;
    if (div_fixed > 0xFFFFFF) div_fixed = 0xFFFFFF;
    uint16_t div_int = div_fixed >> 8;
    uint8_t div_frac = div_fixed & 0xFF;

    if (running_program == cycles) {
        // Same program already running: just retune, no glitch on the pin.
        // The new divider takes effect on the next PIO clock.
        pio_sm_set_clkdiv_int_frac8(pio, sm, div_int, div_frac);
    } else {
        start_program(cycles, div_int, div_frac);
    }

    // Report the frequency the hardware really produces with this divider:
    // clk / (cycles * div_fixed / 256).
    current_hz = clk * 256.0 / ((double)cycles * div_fixed);
    return current_hz;
}

double squarewave_get(void) {
    return current_hz;
}
